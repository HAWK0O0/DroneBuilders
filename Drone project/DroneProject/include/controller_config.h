#pragma once

// ============================================================================
// 飞行控制器配置 - 所有参数调试和常量定义
// ============================================================================
// 修改这些值可以调整无人机的飞行特性。

// ============================================================================
// 遥控接收机 (RC Receiver) 基础配置
// ============================================================================
#define RC_MIN_US       1000   // 遥控最小脉宽 (微秒)
#define RC_MAX_US       2000   // 遥控最大脉宽 (微秒)
#define RC_MID_US       1500   // 遥控中点脉宽 (微秒)

// ============================================================================
// 电机与电调 (ESC) 基础配置
// ============================================================================
#define ESC_MIN_US      1000   // 电调最小脉宽
#define ESC_MAX_US      2000   // 电调最大脉宽
#define ESC_ARM_US      1000   // 电调解锁/锁定脉宽 (启动前)

// ============================================================================
// PID 控制器参数 (PID Controller Gains)
// ============================================================================
// 滚转角控制 (Roll)
#define ROLL_P          1.5f   // 比例系数 (P)
#define ROLL_I          0.05f  // 积分系数 (I)
#define ROLL_D          0.3f   // 微分系数 (D)

// 俯仰角控制 (Pitch)
#define PITCH_P         1.5f
#define PITCH_I         0.05f
#define PITCH_D         0.3f

// ============================================================================
// 传感器量程与灵敏度 (Sensor Scale)
// ============================================================================
#define IMU_GYRO_SCALE  131.0f     // 陀螺仪灵敏度
#define IMU_ACCEL_SCALE 16384.0f   // 加速度计灵敏度

#include <Arduino.h>
#include <Adafruit_BNO055.h>

// ============================================================================
// 诊断开关与调试选项
// ============================================================================
#define GPS_DEBUG 0              // GPS 调试信息开关
#define BNO_DEBUG 1              // 指南针与 IMU 调试信息开关
#define STATUS_DEBUG 0           // 系统状态打印开关

// GPS 与串口调试共享 D0/D1 硬件串口
#define GPS_SERIAL Serial

namespace Config {

constexpr uint8_t PIN_NONE = 0xFF;  // 未连接引脚占位符

// ============================================================================
// 接收机 PWM 输入引脚配置
// ============================================================================
// 接收机接线新方案：
// CH1 D2  -> 滚转 (Roll) - 左右移动
// CH2 D4  -> 俯仰 (Pitch) - 前后移动
// CH3 D5  -> 油门 (Throttle)
// CH4 D6  -> 偏航 (Yaw) - 左右转向
// CH5 D7  -> 三段开关:
//            低 = 手动模式, 中 = 平衡辅助, 高 = 自动调平
// CH6 D8  -> 两段开关 (1000/2000) [系统解锁/锁定开关]
constexpr uint8_t PIN_CH1 = 2;
constexpr uint8_t PIN_CH2 = 4;
constexpr uint8_t PIN_CH3 = 5;
constexpr uint8_t PIN_CH4 = 6;
constexpr uint8_t PIN_CH5 = 7;
constexpr uint8_t PIN_CH6 = 8;
constexpr uint8_t PIN_CH7 = PIN_NONE;  // 未使用
constexpr uint8_t PIN_CH8 = PIN_NONE;  // 未使用

// ============================================================================
// 电机电调 (ESC) PWM 输出引脚配置
// ============================================================================
// 注意：为了实现所有通道上升沿的绝对同步，所有 ESC 输出必须位于 AVR 的同一端口。
// ESC1 已从 D3 移至 D12 (PB4)，这样所有四个引脚 (D12, D9, D10, D11) 都在
// PORTB 端口，可以通过一次原子操作同时设置，消除各电机间的微小启动延迟。
constexpr uint8_t PIN_ESC1 = 12;  // 从 D3 移至 D12 (PB4)
constexpr uint8_t PIN_ESC2 = 9;
constexpr uint8_t PIN_ESC3 = 10;
constexpr uint8_t PIN_ESC4 = 11;

// ============================================================================
// GPS 与 BNO055 校准配置
// ============================================================================
constexpr uint32_t GPS_BAUD = 9600;      // GPS 通信波特率

// BNO055 I2C 地址 - 取决于传感器模块型号
constexpr uint8_t BNO_ADDR_A = 0x28;     // 默认地址 A
constexpr uint8_t BNO_ADDR_B = 0x29;     // 备选地址 B
constexpr adafruit_bno055_opmode_t BNO_MODE = OPERATION_MODE_IMUPLUS;


// ============================================================================
// 遥控器脉宽范围 (RC Range) - 微秒
// ============================================================================
// PWM 接收机通常发送 ~1000µs (最小) 到 ~2000µs (最大) 的信号。
// 这些值用于输入信号的滤波和限幅。
constexpr uint16_t RC_MIN = 800;       // 信号下限
constexpr uint16_t RC_MID = 1500;      // 信号中点（中轴）
constexpr uint16_t RC_MAX = 2200;      // 信号上限

// ============================================================================
// 电调输出范围 (ESC Output Range) - 微秒
// ============================================================================
// 这两个值代表电机停止和 100% 全速时的脉冲宽度。
// 输出到电调的信号将以此范围进行映射和限幅。
constexpr uint16_t ESC_STOP = 1000;    // 电机停止信号
constexpr uint16_t ESC_MAX = 2000;     // 电机最大全速信号

// ============================================================================
// 电调更新频率 (ESC Frame Rate)
// ============================================================================
// 20000µs = 50Hz (传统频率)
// 5000µs = 200Hz (平滑响应)
// 2500µs = 400Hz (部分旧电调可能抖动)
// 现代电调多支持 400Hz，目前设置为 200Hz 以兼顾稳定性。
constexpr uint16_t ESC_FRAME_US = 5000; 

// ============================================================================
// 额外控制选项
// ============================================================================
// 可选：将油门信号直接直通到所有电机
constexpr bool DIRECT_ESC_PASSTHROUGH = false;

// 诊断模式：启用后，向所有电机发送相同的固定脉冲。
// 用于检查 D12/D9/D10/D11 之间的时序同步性。
constexpr bool ESC_DIAG_EQUAL_OUTPUTS = false;
constexpr uint16_t ESC_DIAG_OUTPUT_US = 1050;

// ============================================================================
// 电机启动补偿 (Motor Start Compensation) - 可选
// ============================================================================
constexpr bool ESC_START_COMP_ENABLED = false; // 已禁用，避免引起电机抖动
constexpr uint16_t ESC1_START_US = ESC_START_COMP_ENABLED ? 1069 : ESC_STOP;
constexpr uint16_t ESC2_START_US = ESC_START_COMP_ENABLED ? 1066 : ESC_STOP;
constexpr uint16_t ESC3_START_US = ESC_START_COMP_ENABLED ? 1070 : ESC_STOP;
constexpr uint16_t ESC4_START_US = ESC_START_COMP_ENABLED ? 1080 : ESC_STOP;

// 每个电机的最高速度限制
constexpr uint16_t ESC1_MAX_US = ESC_MAX;
constexpr uint16_t ESC2_MAX_US = ESC_MAX;
constexpr uint16_t ESC3_MAX_US = ESC_MAX;
constexpr uint16_t ESC4_MAX_US = ESC_MAX;

// ============================================================================
// 电机微调 (Motor Trim)
// ============================================================================
// 添加或减去这些值以平衡四个电机之间的转速差异
constexpr int ESC_TRIM1 = 0;   // 电机 1
constexpr int ESC_TRIM2 = 0;   // 电机 2
constexpr int ESC_TRIM3 = 0;   // 电机 3
constexpr int ESC_TRIM4 = 0;   // 电机 4

// ============================================================================
// 电机 2 (D9) 启动同步辅助
// ============================================================================
// 在怠速时提供微小增压，以确保 ESC2 与其他电机同步启动。
constexpr uint16_t ESC2_SYNC_BOOST_US = 0;        // 目前已禁用
constexpr uint16_t ESC2_SYNC_BOOST_MAX_US = 1120;

// ============================================================================
// 系统解锁与开关阈值
// ============================================================================
constexpr uint16_t ARM_SW_ON = 1700;   // 开关解锁阈值
constexpr uint16_t ARM_SW_OFF = 1300;  // 开关锁定阈值
constexpr uint16_t SW_OFF = 1300;      // 逻辑关阈值
constexpr uint16_t SW_ON = 1700;       // 逻辑开阈值

// ============================================================================
// 混控器调参 (Mixer Tuning)
// ============================================================================
// 降低响应灵敏度以减少电机的剧烈震荡
constexpr float MIX_SCALE = 0.6f;      // 从 0.45 调高以增强响应

// 电调输出的速率限制器 (Slew Limiter)
// 避免信号突变 - 数值越高响应越快
constexpr int ESC_STEP = 16;           // 从 8 调高以降低抖动感

// 摇杆中心死区 (Stick Deadband)
// 用于过滤遥控器的摇杆噪声和微小回中偏差
constexpr int STICK_DEADBAND_US = 30;  // 从 12 调高以提供更干净的输入

// ============================================================================
// 自动调平 (Auto-Level) 配置
// ============================================================================
constexpr float AUTO_KP = 1.5f;        // 修正增益 - 较低值可使修正更平滑
constexpr int AUTO_MAX = 150;          // 最大修正幅度限制
constexpr int AUTO_DEADBAND_US = 120;  // 修正死区
constexpr uint16_t AUTO_MIN_THR = 50;  // 启用自动调平的最低油门阈值

// ============================================================================
// 滤波与速率限制参数
// ============================================================================
// 每循环内修正量的最大变化限制 - 避免产生由于修正引起的冲击
constexpr int AUTO_CORR_SLEW_STEP = 20; // 从 8 调高以加快修正响应

// IMU 欧拉角的低通滤波器 (Low-pass Filter) 系数
// 范围: [0..1]，值越高响应越快，但滤波能力越弱
constexpr float IMU_EULER_LPF_ALPHA = 0.25f;

// ============================================================================
// 轴向与方向校正 (IMU Axis Alignment)
// ============================================================================
// 如需反向，请将值修改为 (-1)
constexpr int IMU_ROLL_SIGN = 1;       // 滚转轴符号
constexpr int IMU_PITCH_SIGN = 1;      // 俯仰轴符号
constexpr int IMU_YAW_SIGN = 1;        // 偏航轴符号

// ============================================================================
// IMU 校准阈值 (Calibration Thresholds)
// ============================================================================
// 传感器自检必须达到的最小校准等级 (0 = 不检查)
constexpr uint8_t CAL_SYS_MIN = 0;      // 系统整体
constexpr uint8_t CAL_GYRO_MIN = 1;     // 陀螺仪
constexpr uint8_t CAL_ACCEL_MIN = 1;    // 加速度计
constexpr uint8_t CAL_MAG_MIN = 0;      // 磁力计

// ============================================================================
// 失控保护 (Failsafe)
// ============================================================================
// 失去接收机信号后进入失控保护的超时时间 (微秒)
constexpr uint32_t FAILSAFE_US = 300000; // 300 毫秒

}  // namespace Config